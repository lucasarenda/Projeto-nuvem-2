-- DoaPerto - esquema inicial
-- ongs 1:N necessidades | doadores 1:N doacoes | necessidades 1:N doacoes
-- (doadores N:N necessidades através de doacoes)

CREATE TABLE ongs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(150)     NOT NULL,
    cnpj           VARCHAR(18)      UNIQUE,
    email          VARCHAR(150)     NOT NULL,
    telefone       VARCHAR(20),
    descricao      VARCHAR(2000),
    endereco       VARCHAR(255),
    cidade         VARCHAR(100)     NOT NULL,
    uf             VARCHAR(2)       NOT NULL,
    latitude       DOUBLE PRECISION NOT NULL,
    longitude      DOUBLE PRECISION NOT NULL,
    logo_key       VARCHAR(500),
    criado_em      TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE necessidades (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ong_id               BIGINT       NOT NULL REFERENCES ongs (id) ON DELETE CASCADE,
    titulo               VARCHAR(150) NOT NULL,
    descricao            VARCHAR(2000),
    categoria            VARCHAR(20)  NOT NULL,
    quantidade           INTEGER      NOT NULL CHECK (quantidade > 0),
    quantidade_recebida  INTEGER      NOT NULL DEFAULT 0 CHECK (quantidade_recebida >= 0),
    unidade              VARCHAR(20)  NOT NULL,
    urgencia             VARCHAR(10)  NOT NULL,
    status               VARCHAR(15)  NOT NULL DEFAULT 'ABERTA',
    origem               VARCHAR(10)  NOT NULL DEFAULT 'MANUAL',
    criado_em            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_necessidade_categoria CHECK (categoria IN ('ALIMENTO', 'ROUPA', 'CALCADO', 'HIGIENE', 'COBERTOR', 'BRINQUEDO', 'OUTRO')),
    CONSTRAINT ck_necessidade_urgencia  CHECK (urgencia IN ('BAIXA', 'MEDIA', 'ALTA')),
    CONSTRAINT ck_necessidade_status    CHECK (status IN ('ABERTA', 'ATENDIDA', 'CANCELADA')),
    CONSTRAINT ck_necessidade_origem    CHECK (origem IN ('MANUAL', 'CSV'))
);
CREATE INDEX ix_necessidades_ong ON necessidades (ong_id);
CREATE INDEX ix_necessidades_categoria_status ON necessidades (categoria, status);

CREATE TABLE doadores (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(150) NOT NULL,
    email          VARCHAR(150) NOT NULL UNIQUE,
    telefone       VARCHAR(20),
    cidade         VARCHAR(100),
    uf             VARCHAR(2),
    latitude       DOUBLE PRECISION,
    longitude      DOUBLE PRECISION,
    criado_em      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE doacoes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doador_id       BIGINT        NOT NULL REFERENCES doadores (id) ON DELETE CASCADE,
    necessidade_id  BIGINT        NOT NULL REFERENCES necessidades (id) ON DELETE CASCADE,
    descricao       VARCHAR(500)  NOT NULL,
    quantidade      INTEGER       NOT NULL CHECK (quantidade > 0),
    status          VARCHAR(15)   NOT NULL DEFAULT 'PENDENTE',
    distancia_km    NUMERIC(8, 2),
    observacao      VARCHAR(1000),
    criado_em       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_doacao_status CHECK (status IN ('PENDENTE', 'CONFIRMADA', 'ENTREGUE', 'CANCELADA'))
);
CREATE INDEX ix_doacoes_doador ON doacoes (doador_id);
CREATE INDEX ix_doacoes_necessidade ON doacoes (necessidade_id);

-- Arquivos enviados ao S3 (fotos, PDFs). A Lambda "processar-arquivo" preenche
-- largura/altura/paginas/thumbnail_key e muda o status para PROCESSADO.
CREATE TABLE anexos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidade_tipo   VARCHAR(20)  NOT NULL,
    entidade_id     BIGINT       NOT NULL,
    nome_original   VARCHAR(255) NOT NULL,
    s3_key          VARCHAR(500) NOT NULL UNIQUE,
    content_type    VARCHAR(100) NOT NULL,
    tamanho_bytes   BIGINT,
    status          VARCHAR(20)  NOT NULL DEFAULT 'AGUARDANDO_UPLOAD',
    largura         INTEGER,
    altura          INTEGER,
    paginas         INTEGER,
    thumbnail_key   VARCHAR(500),
    erro            VARCHAR(1000),
    processado_em   TIMESTAMP,
    criado_em       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_anexo_entidade CHECK (entidade_tipo IN ('ONG', 'NECESSIDADE', 'DOACAO')),
    CONSTRAINT ck_anexo_status   CHECK (status IN ('AGUARDANDO_UPLOAD', 'PROCESSADO', 'ERRO'))
);
CREATE INDEX ix_anexos_entidade ON anexos (entidade_tipo, entidade_id);

-- Importação de necessidades em lote via CSV. A Lambda lê o arquivo do S3,
-- grava as linhas em "necessidades" e o resumo aqui.
CREATE TABLE importacoes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ong_id             BIGINT       NOT NULL REFERENCES ongs (id) ON DELETE CASCADE,
    nome_arquivo       VARCHAR(255) NOT NULL,
    s3_key             VARCHAR(500) NOT NULL UNIQUE,
    status             VARCHAR(20)  NOT NULL DEFAULT 'AGUARDANDO_UPLOAD',
    linhas_total       INTEGER,
    linhas_importadas  INTEGER,
    linhas_com_erro    INTEGER,
    mensagens          VARCHAR(4000),
    processado_em      TIMESTAMP,
    criado_em          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_importacao_status CHECK (status IN ('AGUARDANDO_UPLOAD', 'CONCLUIDA', 'ERRO'))
);
CREATE INDEX ix_importacoes_ong ON importacoes (ong_id);
